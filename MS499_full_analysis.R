## ============================ T3  Price chain ================================
t3_rows <- list()
for (code in SP_CODES) {
  nmk  <- length(ret_markets(code)); cn <- cons_n(code)
  prod <- po_mean("Aratdar", "buy_kg",  code, LANDING)
  arat <- po_mean("Aratdar", "sell_kg", code, LANDING)
  bep  <- po_mean("Bepari_Faria", "sell_kg", code)
  ret  <- po_mean("Khuchra", "sell_kg", code)
  cons <- cons_mean(code)
  complete <- all(!is.na(c(prod, arat, bep, cons))) &&
    cn >= MIN_CONS && nmk >= MIN_MARKETS
  reasons <- c()
  if (nmk < MIN_MARKETS) reasons <- c(reasons, sprintf("retail quotes in %d market(s)", nmk))
  if (cn == 0) reasons <- c(reasons, "no consumer quotes")
  else if (cn < MIN_CONS) reasons <- c(reasons,
      sprintf("consumer quotes n=%d (<%d; share not reported)", cn, MIN_CONS))
  dif <- function(a, b) if (is.na(a) || is.na(b)) NA_real_ else round(a - b, 2)
  t3_rows[[code]] <- data.frame(
    Species_code = code, Local_name = SP_LOCAL[[code]],
    English_name = as.character(SP$English_common_name[as.character(SP$Code) == code]),
    n_price_obs = sum(as.character(PO$Species_code) == code &
                        (!is.na(PO$buy_kg) | !is.na(PO$sell_kg))),
    Retail_markets_n = nmk, Consumer_paid_n = cn,
    Reporting_status = if (length(reasons))
      paste0("Descriptive-only (Method 3.8): ", paste(reasons, collapse = "; ")) else "",
    Producer_BDT_kg = prod, Aratdar_sell_BDT_kg = arat,
    Bepari_sell_BDT_kg = bep, Retailer_sell_BDT_kg = ret,
    Consumer_paid_BDT_kg = cons,
    Aratdar_margin_BDT_kg  = if (complete) dif(arat, prod) else NA_real_,
    Bepari_margin_BDT_kg   = if (complete) dif(bep, arat)  else NA_real_,
    Retailer_margin_BDT_kg = if (complete) dif(cons, bep)  else NA_real_,
    Total_spread_BDT_kg    = if (complete) dif(cons, prod) else NA_real_,
    Producer_share_pct     = if (complete) round(100 * prod / cons, 1) else NA_real_,
    stringsAsFactors = FALSE)
}
