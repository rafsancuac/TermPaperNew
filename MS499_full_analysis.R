  kwp <- T14$p_value[T14$Species == code]
  if (length(kwp) == 0 || is.na(kwp) || kwp >= ALPHA) next
  allv <- unlist(cells)
  N <- length(allv); r <- rank(allv)
  tie <- sum(tapply(r, allv, function(g) length(g)^3 - length(g)))
  A <- N * (N + 1) / 12 * (1 - tie / (N^3 - N))
  mr <- tapply(r, rep(names(cells), sapply(cells, length)), mean)
  ns <- sapply(cells, length)
  ms <- names(cells)
  if (length(ms) < 2) next
  for (i in 1:(length(ms) - 1)) for (j in (i + 1):length(ms)) {
    se <- sqrt(A * (1 / ns[ms[i]] + 1 / ns[ms[j]]))
    z <- (mr[[ms[i]]] - mr[[ms[j]]]) / se
    dunn_rows[[length(dunn_rows) + 1]] <- data.frame(
      Market_i = ms[i], Market_j = ms[j], z = round(z, 3),
      raw_p = round(2 * pnorm(-abs(z)), 4), Species = code, stringsAsFactors = FALSE)
  }
}
T14b <- if (length(dunn_rows)) {
  d <- do.call(rbind, dunn_rows)
  d$p_holm <- NA_real_
  for (sp in unique(d$Species)) {
    ix <- which(d$Species == sp)
    d$p_holm[ix] <- round(p.adjust(d$raw_p[ix], method = "holm"), 4)
  }
  d$significant_0.05 <- ifelse(d$p_holm < ALPHA, "True", "False")
  d[order(d$Species, d$raw_p), c("Market_i", "Market_j", "z", "raw_p", "p_holm",
                                 "significant_0.05", "Species")]
} else data.frame(Market_i = character(0))
