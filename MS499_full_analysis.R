## Methodology 3.7.1: MC = sum of itemised expenses / quantity per day.
resp_buy_px <- function(rid) {
  v <- PO$buy_kg[as.character(PO$Respondent_ID) == rid]; v <- v[!is.na(v)]
  if (!length(v)) NA_real_ else mean(v)
