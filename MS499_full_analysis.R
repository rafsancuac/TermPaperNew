  loss <- as_num(FR$Spoilage_pct) / 100 * buy * cap; loss[is.na(loss)] <- 0
  data.frame(Stratum = "Khuchra retailer", cap = cap, total = rent + ice + wash + loss,
             stringsAsFactors = FALSE)
}
