mc_aratdar <- function() {
  cap <- as_num(FA$Daily_capacity_kg)
  rent  <- mapply(per_day, FA$Rent_amount_BDT, FA$Rent_frequency)
  elec  <- mapply(per_day, FA$Electricity_bill_BDT, FA$Electricity_frequency)
  maint <- mapply(per_day, FA$Equipment_Cooler_Maintenance_BDT,
                  FA$Equipment_Cooler_Maintenance_frequency)
  wages <- as_num(FA$Workers_count) * as_num(FA$Worker_daily_wage_BDT)
  other <- mapply(per_day, FA$Other_cost_BDT, "Monthly")
  tot <- rent + elec + maint + wages + other
  data.frame(Stratum = "Aratdar", cap = cap, total = tot,
             stringsAsFactors = FALSE)
}
mc_bepari <- function() {
  cap <- as_num(FB$Daily_capacity_kg)
  period <- as_num(FB$Trip_frequency_days); period[is.na(period) | period <= 0] <- 1
  trips  <- as_num(FB$Trips_per_period);    trips[is.na(trips)] <- 0
  transport <- (as_num(FB$Transport_fare_per_trip_BDT) +
                  as_num(FB$Loading_Unloading_cost_per_trip_BDT)) * trips / period
  ice  <- as_num(FB$Ice_cost_BDT_per_day); ice[is.na(ice)] <- 0
  buy  <- sapply(as.character(FB$Respondent_ID), resp_buy_px)
  buy[is.na(buy)] <- 0
  unit <- tolower(as.character(FB$Commission_unit))
  cval <- as_num(FB$Commission_to_aratdar_value); cval[is.na(cval)] <- 0
  comm <- ifelse(grepl("^percent", unit), cval / 100 * buy * cap, cval * trips / period)
  loss <- as_num(FB$Transit_damage_pct) / 100 * buy * cap
  loss[is.na(loss)] <- 0
  data.frame(Stratum = "Bepari/Faria", cap = cap,
             total = transport + ice + comm + loss, stringsAsFactors = FALSE)
}
mc_retail <- function() {
  cap <- as_num(FR$Daily_capacity_kg)
  rent <- as_num(FR$Shop_Van_Rent_BDT_per_day); rent[is.na(rent)] <- 0
  ice  <- as_num(FR$Ice_cost_BDT_per_day);      ice[is.na(ice)] <- 0
