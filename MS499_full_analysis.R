## Counter.most_common() equivalent: count descending, ties in first-appearance order
most_common <- function(x) {
  x <- as.character(x); x <- x[!is.na(x) & x != ""]
  u <- unique(x)                                   ## first-appearance order
  n <- vapply(u, function(k) sum(x == k), integer(1))
  ord <- order(-n, seq_along(u))                   ## count desc, ties keep order
  list(keys = u[ord], n = as.integer(n[ord]), total = length(x))
}
chan <- function(form, field, fixed_order = NULL) {
  mc <- most_common(if (form == "B") FB[[field]] else FR[[field]])
  keys <- if (!is.null(fixed_order)) fixed_order else mc$keys
  ns <- setNames(mc$n, mc$keys)
  ## A fixed order is reported in full: a category with zero observations is
  ## still shown (n = 0), which is what makes "no retailer sells entirely on
  ## cash" a visible result rather than a silent omission.
  ns <- vapply(keys, function(k) if (k %in% names(ns)) ns[[k]] else 0L, integer(1))
  data.frame(Form = if (form == "B") "Form B (Bepari/Faria)" else "Form R (Retailer)",
             Field = gsub("_", " ", field), Value = keys,
             n = as.integer(ns), pct = pct(as.integer(ns), mc$total),
             stringsAsFactors = FALSE)
}
