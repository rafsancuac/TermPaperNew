as_num <- function(x) suppressWarnings(as.numeric(as.character(x)))

## BDT per kg, with fallback recomputation from the raw quote (Methodology 3.2)
ppk <- function(raw, unit, cached) {
  v <- as_num(cached)
  out <- ifelse(!is.na(v), round(v, 2), NA_real_)
  r <- as_num(raw)
  u <- tolower(as.character(unit))
  fb <- ifelse(!is.na(r),
               ifelse(!is.na(u) & u == "maund", round(r / MAUND, 2), round(r, 2)),
               NA_real_)
  ifelse(is.na(out), fb, out)
}

## quantity in kg, with fallback (maund -> kg multiplies)
qkg <- function(raw, unit, cached) {
  v <- as_num(cached)
  out <- ifelse(!is.na(v), round(v, 2), NA_real_)
  r <- as_num(raw)
  u <- tolower(as.character(unit))
  fb <- ifelse(!is.na(r),
               ifelse(!is.na(u) & u == "maund", round(r * MAUND, 2), round(r, 2)),
               NA_real_)
  ifelse(is.na(out), fb, out)
}

## bind data frames that do not share all columns, on their intersection
rbind_common <- function(lst) {
  cn <- Reduce(intersect, lapply(lst, names))
  do.call(rbind, lapply(lst, function(d) d[, cn, drop = FALSE]))
}

mean_sd <- function(x, nd = 2) {
  x <- x[!is.na(x)]
  if (!length(x)) return(c(NA, NA, 0))
  c(round(mean(x), nd),
    if (length(x) > 1) round(sd(x), nd) else 0,
    length(x))
}

pct <- function(k, n, nd = 1) if (!n) 0 else round(100 * k / n, nd)

## convert a mixed-frequency cost item to BDT per trading day
per_day <- function(amount, freq, default_days = 1) {
  v <- as_num(amount)
  if (is.na(v) || v <= 0) return(0)
  f <- tolower(as.character(freq)); f <- ifelse(is.na(f), "", f)
  if (grepl("^day", f)) v
  else if (grepl("^month", f)) v / TRADING_DAYS_MONTH
  else if (grepl("^year", f) || grepl("^annual", f)) v / TRADING_DAYS_YEAR
  else if (grepl("^week", f)) v / 6
  else v / default_days
}

